import { Navigate, createBrowserRouter } from 'react-router'
import { RegisterPage, LoginPage } from '../features/auth'

export const router = createBrowserRouter([
  {
    path: '/register',
    element: <RegisterPage />,
  },
  {
    path: '/login',
    element: <LoginPage />,
  },
  {
    path: '*',
    element: <Navigate to="/login" replace />,
  },
])
